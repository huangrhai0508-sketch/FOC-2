cbkfile = fileread([mdlRoot '\utilities\ComConf\Com_Cbk_Adap.c']);
cbkfilehandle = fopen('Com_Cbk_Adap.c','w');
%cbkfile = char(fread(cbkfilehandle)');
key1 = 'void ';
key2 = '(void)';
   
keystart = findstr(cbkfile,key1);
keystop = findstr(cbkfile,key2);
%    for i = 2: length(keystop)
%        funend(i-1) = keystart(i);
%    end
%    funend(i) = length(cbkfile);
clear newcbkfile;
newcbkfile = cbkfile;
if (length(keystart) == length(keystop)) &&(~isempty(keystart))
    for funCnt = 1:length(keystart)     
        tmpfindkey1 = findstr(newcbkfile,key1);
        tmpfindkey2 = findstr(newcbkfile,key2);
        funStart = tmpfindkey1(funCnt);       % void postion
        funMid  =  tmpfindkey2(funCnt);       %first ( position
        if funCnt == length(keystart)
            funEnd = length(newcbkfile);
        else
          funEnd = tmpfindkey1(funCnt+1);   % Last } position
        end
              
        funDef = newcbkfile(funStart+length(key1):funMid-1);
        if startsWith(funDef,'Com_RxCbk')
            funCbk = ['    ',replace(funDef,'Com_RxCbk','get'),'();',newline];
        elseif startsWith(funDef,'Com_TxCbk')
            funCbk = ['    ',replace(funDef,'Com_TxCbk','set'),'();',newline];
        else
            funCbk = [];
        end
        % fill the funCbk into the positioned {}
        % only one pair {} in the function 

        firstBracket = funStart + min(findstr(newcbkfile(funStart:funEnd),'{'));
        lastBracket = funStart + max(findstr(newcbkfile(funStart:funEnd),'}'))-1;

        newcbkfile = [newcbkfile(1:firstBracket),...
                        funCbk,...
                        newcbkfile(lastBracket:length(newcbkfile)) ];               
       end
   end
   % insert #include "Adp_can.h" 
   includepos = min(findstr(newcbkfile,'#include'));
   insertData = ['#include "Adp_com.h"', newline()];
   if isempty(strfind(newcbkfile,insertData))
        if includepos==1
             insertBefore = [];
            insertAfter = newcbkfile;
        else
            insertBefore = newcbkfile(1:includepos-1);
            insertAfter = newcbkfile(includepos: length(newcbkfile));
        end
        newcbkfile= [insertBefore, insertData, insertAfter];
   end
   fprintf(cbkfilehandle,'//%s    :',char(datetime));
   fprintf(cbkfilehandle,'//Updated by %s.m\n',mfilename('fullpath'));
   fprintf(cbkfilehandle,'%s',newcbkfile);
   fclose(cbkfilehandle);   
%end
